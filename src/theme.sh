if test -n "${_tuish_theme_loaded:-}"; then return 0; fi
_tuish_theme_loaded=1

TUISH_THEME_NAME=cyber
TUISH_THEME_BG=0
TUISH_THEME_SURFACE=17
TUISH_THEME_SURFACE_ALT=18
TUISH_THEME_TEXT=255
TUISH_THEME_MUTED=245
TUISH_THEME_PRIMARY=51
TUISH_THEME_SECONDARY=141
TUISH_THEME_SUCCESS=42
TUISH_THEME_WARNING=220
TUISH_THEME_DANGER=203
TUISH_THEME_BORDER=60
TUISH_THEME_FOCUS=45

tuish_theme_use () {
  case "$1" in
    cyber)
      TUISH_THEME_NAME=cyber
      TUISH_THEME_BG=0 TUISH_THEME_SURFACE=17 TUISH_THEME_SURFACE_ALT=18
      TUISH_THEME_TEXT=255 TUISH_THEME_MUTED=245 TUISH_THEME_PRIMARY=51
      TUISH_THEME_SECONDARY=141 TUISH_THEME_SUCCESS=42 TUISH_THEME_WARNING=220
      TUISH_THEME_DANGER=203 TUISH_THEME_BORDER=60 TUISH_THEME_FOCUS=45 ;;
    midnight)
      TUISH_THEME_NAME=midnight
      TUISH_THEME_BG=0 TUISH_THEME_SURFACE=16 TUISH_THEME_SURFACE_ALT=235
      TUISH_THEME_TEXT=252 TUISH_THEME_MUTED=244 TUISH_THEME_PRIMARY=39
      TUISH_THEME_SECONDARY=99 TUISH_THEME_SUCCESS=78 TUISH_THEME_WARNING=214
      TUISH_THEME_DANGER=203 TUISH_THEME_BORDER=238 TUISH_THEME_FOCUS=33 ;;
    mono)
      TUISH_THEME_NAME=mono
      TUISH_THEME_BG=0 TUISH_THEME_SURFACE=0 TUISH_THEME_SURFACE_ALT=0
      TUISH_THEME_TEXT=15 TUISH_THEME_MUTED=8 TUISH_THEME_PRIMARY=15
      TUISH_THEME_SECONDARY=7 TUISH_THEME_SUCCESS=15 TUISH_THEME_WARNING=15
      TUISH_THEME_DANGER=15 TUISH_THEME_BORDER=7 TUISH_THEME_FOCUS=15 ;;
    *) return 2 ;;
  esac
}

tuish_theme_set () {
  local _th_token=$1 _th_value=$2
  case "$_th_value" in ''|*[!0-9]*) return 2;; esac
  test "$_th_value" -le 255 || return 2
  case "$_th_token" in
    bg) TUISH_THEME_BG=$_th_value;; surface) TUISH_THEME_SURFACE=$_th_value;;
    surface_alt) TUISH_THEME_SURFACE_ALT=$_th_value;; text) TUISH_THEME_TEXT=$_th_value;;
    muted) TUISH_THEME_MUTED=$_th_value;; primary) TUISH_THEME_PRIMARY=$_th_value;;
    secondary) TUISH_THEME_SECONDARY=$_th_value;; success) TUISH_THEME_SUCCESS=$_th_value;;
    warning) TUISH_THEME_WARNING=$_th_value;; danger) TUISH_THEME_DANGER=$_th_value;;
    border) TUISH_THEME_BORDER=$_th_value;; focus) TUISH_THEME_FOCUS=$_th_value;;
    *) return 2 ;;
  esac
}

tuish_theme_get () {
  case "$1" in
    bg) TUISH_THEME_VALUE=$TUISH_THEME_BG;; surface) TUISH_THEME_VALUE=$TUISH_THEME_SURFACE;;
    surface_alt) TUISH_THEME_VALUE=$TUISH_THEME_SURFACE_ALT;; text) TUISH_THEME_VALUE=$TUISH_THEME_TEXT;;
    muted) TUISH_THEME_VALUE=$TUISH_THEME_MUTED;; primary) TUISH_THEME_VALUE=$TUISH_THEME_PRIMARY;;
    secondary) TUISH_THEME_VALUE=$TUISH_THEME_SECONDARY;; success) TUISH_THEME_VALUE=$TUISH_THEME_SUCCESS;;
    warning) TUISH_THEME_VALUE=$TUISH_THEME_WARNING;; danger) TUISH_THEME_VALUE=$TUISH_THEME_DANGER;;
    border) TUISH_THEME_VALUE=$TUISH_THEME_BORDER;; focus) TUISH_THEME_VALUE=$TUISH_THEME_FOCUS;;
    *) return 2 ;;
  esac
}
